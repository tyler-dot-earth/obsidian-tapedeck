import { assert, describe, it } from '@effect/vitest'
import type { Schema } from 'effect'

import {
	clampTitle,
	codexThreadNames,
	fallbackTitle,
	harnessName,
	readPrompt,
	tapeTitle,
} from '#/src/tapedeck-tape-title'

const prompt = (text: string): string | undefined => {
	const piece = readPrompt(text)

	return piece.kind === 'prompt' ? piece.text : undefined
}

const json = (value: Schema.Json): string => JSON.stringify(value)

describe('readPrompt', () => {
	it('keeps plain prompts, collapsing whitespace', () => {
		assert.strictEqual(prompt('  Fix the\n\n  flaky   test '), 'Fix the flaky test')
	})

	it('skips Claude Code command, output, and notice wrappers', () => {
		const clear =
			'<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>'

		assert.deepStrictEqual(readPrompt(clear), { kind: 'command', name: '/clear' })
		assert.deepStrictEqual(readPrompt('<local-command-stdout>done</local-command-stdout>'), {
			kind: 'skip',
		})

		assert.deepStrictEqual(
			readPrompt('Caveat: The messages below were generated by the user while running commands.'),
			{ kind: 'skip' },
		)

		assert.deepStrictEqual(
			readPrompt(
				'<task-notification><task-id>t1</task-id><status>done</status><summary>ok</summary></task-notification>',
			),
			{ kind: 'skip' },
		)

		assert.deepStrictEqual(readPrompt('<bash-stdout></bash-stdout><bash-stderr>x</bash-stderr>'), {
			kind: 'skip',
		})
	})

	it('titles a command that has arguments', () => {
		assert.strictEqual(
			prompt(
				'<command-message>review</command-message><command-name>/review</command-name><command-args>the login flow</command-args>',
			),
			'/review the login flow',
		)
	})

	it('keeps pasted text and shell input', () => {
		assert.strictEqual(
			prompt('<pasted_content id="p1">Sort the mixtape list by date</pasted_content>'),
			'Sort the mixtape list by date',
		)

		assert.strictEqual(
			prompt('<pasted_content id="p2">Error: boom</pasted_content> why does this fail?'),
			'Error: boom why does this fail?',
		)

		assert.strictEqual(prompt('<bash-input>ls -la</bash-input>'), '! ls -la')
	})

	it('drops Codex context blocks and keeps what follows', () => {
		assert.deepStrictEqual(
			readPrompt('<environment_context><cwd>/home/sample/mixtape</cwd></environment_context>'),
			{ kind: 'skip' },
		)

		assert.strictEqual(
			prompt(
				'<in-app-browser-context source="ambient-ui-state">tab: docs</in-app-browser-context>\nSummarise this page',
			),
			'Summarise this page',
		)

		assert.strictEqual(
			prompt(
				'<realtime_delegation><source>voice</source><input>Add a dark mode</input><transcript_delta>add a dark</transcript_delta></realtime_delegation>',
			),
			'Add a dark mode',
		)

		assert.deepStrictEqual(readPrompt('<user_instructions>Be brief</user_instructions>'), {
			kind: 'skip',
		})

		assert.deepStrictEqual(readPrompt('<recommended_plugins>a, b</recommended_plugins>'), {
			kind: 'skip',
		})

		assert.deepStrictEqual(readPrompt('<image name="[Image #1]">'), { kind: 'skip' })
	})

	it('skips AGENTS.md injections and the Codex history preamble', () => {
		assert.deepStrictEqual(
			readPrompt('# AGENTS.md instructions for /home/sample/mixtape\n\nUse tabs.'),
			{
				kind: 'skip',
			},
		)

		assert.deepStrictEqual(
			readPrompt(
				'The following is the Codex agent history whose request action you are reviewing.',
			),
			{ kind: 'skip' },
		)
	})

	it('strips leftover tags', () => {
		assert.strictEqual(prompt('<reply>Yes, ship it</reply>'), 'Yes, ship it')
		assert.deepStrictEqual(readPrompt('<empty></empty>'), { kind: 'skip' })
	})
})

describe('tapeTitle', () => {
	const clear = '<command-name>/clear</command-name><command-args></command-args>'

	it('prefers the harness name', () => {
		assert.deepStrictEqual(tapeTitle('Greeting fix', ['Make it say hello']), {
			title: 'Greeting fix',
			source: 'name',
		})
	})

	it('uses the first real prompt, skipping wrappers', () => {
		assert.deepStrictEqual(tapeTitle(undefined, [clear, 'Caveat: x', 'Make it say hello']), {
			title: 'Make it say hello',
			source: 'prompt',
		})

		assert.deepStrictEqual(tapeTitle('  ', ['Make it say hello']).source, 'prompt')
	})

	it('falls back to the commands run, or an empty tape', () => {
		assert.deepStrictEqual(tapeTitle(undefined, [clear, clear]), {
			title: '/clear only',
			source: 'fallback',
		})

		assert.strictEqual(tapeTitle(undefined, []).title, 'empty tape')
		assert.strictEqual(fallbackTitle(['/clear', '/model']), '/clear /model only')
	})

	it('shortens long titles', () => {
		const title = clampTitle('word '.repeat(40))
		assert.isAtMost(title.length, 72)
		assert.isTrue(title.endsWith('…'))
	})
})

describe('harnessName', () => {
	it('reads Claude Code custom titles before generated ones, latest first', () => {
		const lines = [
			json({ type: 'summary', summary: 'Old summary', leafUuid: 'u1' }),
			json({ type: 'ai-title', aiTitle: 'Generated one', sessionId: 's' }),
			json({ type: 'custom-title', customTitle: 'My name', sessionId: 's' }),
			json({ type: 'ai-title', aiTitle: 'Generated two', sessionId: 's' }),
			json({ type: 'custom-title', customTitle: 'My better name', sessionId: 's' }),
		]

		assert.strictEqual(harnessName('claude-code', lines), 'My better name')
		assert.strictEqual(harnessName('claude-code', lines.slice(0, 2)), 'Generated one')
		assert.strictEqual(harnessName('claude-code', lines.slice(0, 1)), 'Old summary')
		assert.isUndefined(harnessName('claude-code', ['not json']))
	})

	it('reads the latest Pi session name, where an empty name clears it', () => {
		const named = json({ type: 'session_info', id: 'a', name: 'Pi mixtape' })
		const cleared = json({ type: 'session_info', id: 'b', name: '' })
		assert.strictEqual(harnessName('pi', [named]), 'Pi mixtape')
		assert.isUndefined(harnessName('pi', [named, cleared]))
	})

	it('reads Codex names from the session index, latest first', () => {
		const names = codexThreadNames([
			json({ id: 'ID-1', thread_name: 'First', updated_at: '2026-01-01T00:00:00Z' }),
			json({ id: 'id-2', thread_name: 'Other', updated_at: '2026-01-01T00:00:00Z' }),
			json({ id: 'id-1', thread_name: 'Renamed', updated_at: '2026-01-02T00:00:00Z' }),
		])

		assert.strictEqual(names.get('id-1'), 'Renamed')
		assert.strictEqual(names.get('id-2'), 'Other')
		assert.isUndefined(harnessName('codex', []))
	})
})
